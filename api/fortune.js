function hashString(str) {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash * 31 + str.charCodeAt(i)) >>> 0;
  }
  return hash;
}

function makeDailyLuck(seed, dateStr) {
  const num = hashString(seed + dateStr);
  return (num % 5) + 1;
}

